<script lang="ts">
	// Reports & backup: PDF summary, CSV exports, JSON backup/import, start fresh.
	import { app } from '$lib/app.svelte.ts';
	import { RANGES, type RangeKey } from '$lib/core/stats.ts';
	import { downloadBackup, downloadCsv, downloadPdfReport, exportableItems } from '$lib/exports.ts';
	import Icon from '$lib/components/Icon.svelte';
	import ConfirmDialog from '$lib/components/ConfirmDialog.svelte';

	let range = $state<RangeKey>('30d');
	let includeConfidential = $state(false);
	let busy = $state('');
	let confirmExport = $state<null | 'pdf' | 'feedback'>(null);
	let freshOpen = $state(false);
	let importing = $state(false);

	const count = $derived(exportableItems(range, includeConfidential).length);
	const confidentialCount = $derived(app.scopedFeedback.filter((f) => f.category === 'Confidential report').length);

	async function run(label: string, fn: () => Promise<void>) {
		busy = label;
		try {
			await fn();
			app.toast(`${label} ready.`, 'success');
		} catch (e) {
			app.toast(e instanceof Error ? e.message : `${label} failed.`, 'error');
		} finally {
			busy = '';
		}
	}

	function startExport(kind: 'pdf' | 'feedback') {
		// Sensitive exports are confirmed first.
		if (includeConfidential && app.isAdmin) {
			confirmExport = kind;
			return;
		}
		void doExport(kind);
	}

	async function doExport(kind: 'pdf' | 'feedback') {
		confirmExport = null;
		if (kind === 'pdf') await run('PDF report', () => downloadPdfReport(range, includeConfidential));
		else await run('Feedback CSV', () => downloadCsv('feedback', range, includeConfidential));
	}

	async function onImport(e: Event) {
		const input = e.currentTarget as HTMLInputElement;
		const file = input.files?.[0];
		if (!file) return;
		importing = true;
		const text = await file.text();
		const res = await app.importBackup(text);
		importing = false;
		input.value = '';
		if (!res.ok) {
			app.toast(res.error ?? 'Import failed.', 'error');
			return;
		}
		app.toast(`Backup imported. Imported accounts use the temporary password ${res.tempPassword}.`, 'success');
	}

	async function startFresh() {
		freshOpen = false;
		const res = await app.startFresh();
		if (!res.ok) {
			app.toast(res.error ?? 'Could not clear the data.', 'error');
			return;
		}
		app.toast('All shared data was cleared.', 'info');
		window.location.href = '/manager';
	}
</script>

<svelte:head><title>Reports - VoiceBox</title></svelte:head>

<h1 data-testid="page-title">Reports &amp; backup</h1>
<p style="max-width:66ch">
	The PDF is generated by a SvelteKit server route; CSV export goes through the same kind of route. Everything else stays in
	the browser.
</p>

<div class="card" style="margin-top:var(--s-4)">
	<div class="card-head"><h2>Export scope</h2><span class="caption num">{count} item(s)</span></div>
	<div class="row" role="group" aria-label="Date range">
		{#each RANGES as r (r.key)}
			<button class="btn sm" class:primary={range === r.key} onclick={() => (range = r.key)} data-testid="rep-range-{r.key}">{r.label}</button>
		{/each}
	</div>
	<p class="caption" style="margin:var(--s-3) 0 0">Scope: {app.isAdmin ? 'all departments' : app.account?.department}.</p>

	{#if app.isAdmin}
		<div class="notice danger" style="margin-top:var(--s-3)">
			<Icon name="shield" size={16} />
			<div style="flex:1">
				<label class="check" style="color:inherit">
					<input type="checkbox" bind:checked={includeConfidential} data-testid="include-confidential" />
					<span>
						<strong>Include confidential reports ({confidentialCount})</strong>
						<span style="display:block; font-size:12px">
							Off by default. Confidential reports are excluded from exports unless you explicitly include them, and you
							will be asked to confirm.
						</span>
					</span>
				</label>
			</div>
		</div>
	{:else}
		<p class="caption" style="margin-top:var(--s-3)">Confidential reports are visible to Admin/HR only and are never included in your exports.</p>
	{/if}
</div>

<div class="grid-3" style="margin-top:var(--s-4)">
	<div class="card">
		<div class="card-head"><h2>PDF summary</h2><Icon name="report" size={18} /></div>
		<p>Period, KPIs, top categories, top issues, resolved items and pulse results. File name: VoiceBox_Report_YYYY-MM.pdf</p>
		<button class="btn primary" onclick={() => startExport('pdf')} disabled={busy !== ''} data-testid="export-pdf">
			<Icon name="download" size={15} />
			{busy === 'PDF report' ? 'Generating...' : 'Download PDF'}
		</button>
	</div>

	<div class="card">
		<div class="card-head"><h2>CSV exports</h2><Icon name="download" size={18} /></div>
		<p>Feedback rows and pulse results. Anonymous items never include author data in the file.</p>
		<div class="row">
			<button class="btn" onclick={() => startExport('feedback')} disabled={busy !== ''} data-testid="export-csv">Feedback CSV</button>
			<button class="btn" onclick={() => run('Pulse CSV', () => downloadCsv('pulse', range, includeConfidential))} disabled={busy !== ''} data-testid="export-pulse-csv">Pulse CSV</button>
		</div>
	</div>

	<div class="card">
		<div class="card-head"><h2>JSON backup</h2><Icon name="upload" size={18} /></div>
		<p>A full snapshot of the shared dataset. Backups never contain passwords or password hashes.</p>
		<div class="row">
			<button class="btn" onclick={() => run('Backup', () => downloadBackup())} data-testid="export-backup">Export backup</button>
			<label class="btn" style="cursor:pointer">
				{importing ? 'Importing...' : 'Import backup'}
				<input type="file" accept="application/json,.json" onchange={onImport} style="display:none" data-testid="import-backup" />
			</label>
		</div>
	</div>
</div>

{#if app.isAdmin}
	<div class="card" style="margin-top:var(--s-4); border-color:var(--red)">
		<div class="card-head"><h2>Start fresh</h2></div>
		<p>Removes every account, feedback item and pulse response stored in this browser. This cannot be undone.</p>
		<button class="btn danger" onclick={() => (freshOpen = true)} data-testid="start-fresh"><Icon name="trash" size={15} /> Start fresh</button>
	</div>
{/if}

<ConfirmDialog
	open={confirmExport !== null}
	title="Export includes confidential reports"
	message="This file will contain {confidentialCount} confidential report(s). Handle it according to your organisation's policy, and do not share it outside Admin/HR."
	confirmLabel="Export anyway"
	danger
	onconfirm={() => confirmExport && doExport(confirmExport)}
	oncancel={() => (confirmExport = null)}
	testid="sensitive-export-dialog"
/>

<ConfirmDialog
	open={freshOpen}
	title="Delete all data in this browser?"
	message="Every account, feedback item, pulse response and notification will be removed FOR EVERYONE on every device. Your admin account is kept so you can sign back in. Export a JSON backup first if you want to keep the data."
	confirmLabel="Delete everything"
	danger
	requireText="DELETE"
	onconfirm={() => void startFresh()}
	oncancel={() => (freshOpen = false)}
	testid="start-fresh-dialog"
/>

<style>
	h1 {
		margin-bottom: var(--s-2);
	}
	.card p {
		font-size: 13px;
	}
</style>
